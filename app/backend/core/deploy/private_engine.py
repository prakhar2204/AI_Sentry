"""
Sentryɸ — Private / Self-Hosted Deploy Engine
core/deploy/private_engine.py

Generates deployment artifacts for self-hosted infrastructure:
  docker_compose → docker-compose.yml + nginx.conf + .env template
  kubernetes     → Kubernetes YAML manifests (Deployment, Service, Ingress, HPA)
  bare_metal     → Shell bootstrap script + systemd service unit

No cloud credentials required — artifacts are generated and saved locally.
The user deploys them to their own infrastructure.

Auth flow: None (no browser OAuth needed)
"""

from __future__ import annotations

import os
import textwrap
from typing import Any

from .base import (
    BaseDeployEngine,
    CredentialResult,
    CredentialStatus,
    DeployPlan,
    DeployResource,
    DeployResult,
    DeployStatus,
    DryRunResult,
    RollbackResult,
)


