BARE_METAL_SCRIPT = """\
#!/usr/bin/env bash
# Sentryɸ — Generated bootstrap script
# Deployment ID: {deployment_id}
# Run as root or with sudo

set -euo pipefail

VENV_DIR="/opt/sentryphi/venv"
APP_DIR="/opt/sentryphi/app"
MODEL_NAME="{model_name}"
PORT={port}

echo "==> Installing system deps..."
apt-get update -qq && apt-get install -y python3.11 python3.11-venv python3-pip curl nginx certbot

echo "==> Creating app directory..."
mkdir -p "$APP_DIR" "$VENV_DIR"
python3.11 -m venv "$VENV_DIR"
"$VENV_DIR/bin/pip" install --quiet fastapi uvicorn

echo "==> Writing systemd service..."
cat > /etc/systemd/system/sentryphi.service << 'EOF'
[Unit]
Description=Sentryɸ Model Server
After=network.target

[Service]
User=www-data
WorkingDirectory={app_dir}
ExecStart={venv_dir}/bin/uvicorn app:app --host 127.0.0.1 --port {port} --workers 2
Restart=always
RestartSec=10
Environment=MODEL_NAME={model_name}

[Install]
WantedBy=multi-user.target
EOF

systemctl daemon-reload
systemctl enable sentryphi
systemctl start sentryphi
echo "==> Sentryɸ model server started on port {port}"
"""


# ─────────────────────────────────────────────
#  Private Deploy Engine
# ─────────────────────────────────────────────

class PrivateDeployEngine(BaseDeployEngine):
    """
    W2.5: Private / self-hosted deployment engine.
    Generates deployment artifacts rather than calling cloud APIs.
    """

    PROVIDER_ID = "private"

    def get_auth_url(self, redirect_port: int = 0) -> str:
        return ""   # No browser auth for private deployments

    def exchange_auth_code(self, code: str, state: str) -> CredentialResult:
        return CredentialResult(
            status  = CredentialStatus.VALID,
            account = "local",
            message = "Private deployment — no cloud authentication required",
        )

    def validate_credentials(self, credentials: dict[str, str]) -> CredentialResult:
        return CredentialResult(
            status  = CredentialStatus.VALID,
            account = "local",
            message = "Private deployment — no credentials required",
        )

    def generate_plan(
        self,
        config: dict[str, Any],
        credentials: dict[str, str],
        scan_report: dict[str, Any],
    ) -> DeployPlan:
        stack = config.get("stack", "docker_compose")

        resources: list[DeployResource] = []
        if stack == "docker_compose":
            resources = [
                DeployResource(resource_type="docker-compose.yml", status="planned"),
                DeployResource(resource_type="nginx.conf",         status="planned"),
                DeployResource(resource_type=".env template",      status="planned"),
            ]
        elif stack == "kubernetes":
            resources = [
                DeployResource(resource_type="Deployment manifest",     status="planned"),
                DeployResource(resource_type="Service manifest",        status="planned"),
                DeployResource(resource_type="Ingress manifest",        status="planned"),
                DeployResource(resource_type="HPA manifest",            status="planned"),
            ]
        elif stack == "bare_metal":
            resources = [
                DeployResource(resource_type="bootstrap.sh",          status="planned"),
                DeployResource(resource_type="sentryphi.service",      status="planned"),
            ]

        security_notes = [
            "TLS termination via Nginx (certificates required)",
            "Rate limiting enabled at reverse proxy level",
            "No cloud provider dependency",
        ]
        if config.get("enable_rate_limiting", True):
            security_notes.append("Rate limiting: configured in nginx/ingress")

        from .recommendation_engine import _COST_ESTIMATES
        cost = _COST_ESTIMATES.get("private", {}).get(stack)

        return DeployPlan(
            provider       = "private",
            region         = "self-hosted",
            resources      = resources,
            estimated_cost = cost.to_dict() if cost else {"low_usd": 10, "high_usd": 50},
            security_notes = security_notes,
            raw_config     = config,
        )

    def estimate_cost(self, plan: DeployPlan, credentials: dict[str, str]) -> dict[str, Any]:
        stack  = plan.raw_config.get("stack", "docker_compose")
        from .recommendation_engine import _COST_ESTIMATES
        static = _COST_ESTIMATES.get("private", {}).get(stack)
        return {**(static.to_dict() if static else {"low_usd": 10, "high_usd": 50}),
                "source": "static_estimate",
                "note": "Server/hardware cost only — no cloud provider fees"}

    def dry_run(self, plan: DeployPlan, credentials: dict[str, str]) -> DryRunResult:
        stack    = plan.raw_config.get("stack", "docker_compose")
        warnings = []

        if stack in ("docker_compose", "kubernetes"):
            try:
                import subprocess
                result = subprocess.run(["docker", "--version"], capture_output=True, timeout=5)
                if result.returncode != 0:
                    warnings.append("Docker not detected on this machine — required for docker_compose/kubernetes")
            except (FileNotFoundError, Exception):
                warnings.append("Docker not found on PATH — install Docker before deploying")

        return DryRunResult(
            success  = True,
            warnings = warnings,
            message  = f"Artifact generation dry run passed for stack: {stack}",
        )

    def deploy(
        self,
        plan: DeployPlan,
        credentials: dict[str, str],
        confirmed: bool = False,
    ) -> DeployResult:
        """Generate deployment artifacts to the output directory."""
        self._require_confirmed(confirmed)

        import datetime
        stack      = plan.raw_config.get("stack", "docker_compose")
        output_dir = credentials.get("output_dir", os.path.join(os.getcwd(), "sentryphi-deploy"))
        os.makedirs(output_dir, exist_ok=True)

        model_image  = plan.raw_config.get("model_image", "python:3.11-slim")
        model_name   = plan.raw_config.get("model_name", "sentryphi-model")
        domain       = plan.raw_config.get("domain", "localhost")
        rate_limit   = plan.raw_config.get("rate_limit_rps", 10)
        timestamp    = datetime.datetime.utcnow().isoformat()
        created: list[DeployResource] = []
        errors:  list[str] = []

        if stack == "docker_compose":
            self._write_docker_compose(
                output_dir, plan.deployment_id, model_image, model_name,
                domain, rate_limit, timestamp, created, errors
            )
        elif stack == "kubernetes":
            self._write_kubernetes(
                output_dir, plan.deployment_id, model_image, model_name,
                domain, rate_limit, plan.raw_config, created, errors
            )
        elif stack == "bare_metal":
            self._write_bare_metal(
                output_dir, plan.deployment_id, model_name, created, errors
            )

        status = DeployStatus.COMPLETE if not errors else DeployStatus.FAILED
        return DeployResult(
            status        = status,
            deployment_id = plan.deployment_id,
            endpoint_url  = f"https://{domain}/predict",
            resources     = created,
            errors        = errors,
            message       = f"Artifacts written to {output_dir}" if not errors else f"{len(errors)} error(s)",
        )

    def _write_docker_compose(
        self,
        out: str,
        dep_id: str,
        image: str,
        model_name: str,
        domain: str,
        rate_limit: int,
        timestamp: str,
        created: list,
        errors: list,
    ) -> None:
        files = {
            "docker-compose.yml": DOCKER_COMPOSE_TEMPLATE.format(
                deployment_id=dep_id,
                timestamp=timestamp,
                model_image=image,
                model_name=model_name,
                max_tokens=2048,
            ),
            "nginx.conf": NGINX_CONF_TEMPLATE.format(
                deployment_id=dep_id,
                domain=domain,
                rate_limit=rate_limit,
            ),
        }
        for fname, content in files.items():
            try:
                path = os.path.join(out, fname)
                with open(path, "w", encoding="utf-8") as f:
                    f.write(content)
                created.append(DeployResource(resource_type=fname, arn_or_id=path, status="created"))
            except Exception as exc:  # noqa: BLE001
                errors.append(f"{fname}: {exc}")

    def _write_kubernetes(
        self,
        out: str,
        dep_id: str,
        image: str,
        model_name: str,
        domain: str,
        rate_limit: int,
        config: dict,
        created: list,
        errors: list,
    ) -> None:
        manifest = K8S_DEPLOYMENT_TEMPLATE.format(
            deployment_id = dep_id,
            namespace     = config.get("k8s_namespace", "sentryphi"),
            model_image   = image,
            model_name    = model_name,
            replicas      = config.get("replicas", 2),
            min_replicas  = config.get("min_replicas", 1),
            max_replicas  = config.get("max_replicas", 5),
            mem_request   = config.get("memory_request", "1Gi"),
            mem_limit     = config.get("memory_limit", "4Gi"),
            cpu_request   = config.get("cpu_request", "500m"),
            cpu_limit     = config.get("cpu_limit", "2"),
            domain        = domain,
            rate_limit    = rate_limit,
        )
        fname = "sentryphi-k8s.yaml"
        try:
            path = os.path.join(out, fname)
            with open(path, "w", encoding="utf-8") as f:
                f.write(manifest)
            created.append(DeployResource(resource_type=fname, arn_or_id=path, status="created"))
        except Exception as exc:  # noqa: BLE001
            errors.append(f"{fname}: {exc}")

    def _write_bare_metal(
        self,
        out: str,
        dep_id: str,
        model_name: str,
        created: list,
        errors: list,
    ) -> None:
        script = BARE_METAL_SCRIPT.format(
            deployment_id = dep_id,
            model_name    = model_name,
            port          = 8000,
            app_dir       = "/opt/sentryphi/app",
            venv_dir      = "/opt/sentryphi/venv",
        )
        fname = "bootstrap.sh"
        try:
            path = os.path.join(out, fname)
            with open(path, "w", encoding="utf-8") as f:
                f.write(script)
            os.chmod(path, 0o755)
            created.append(DeployResource(resource_type=fname, arn_or_id=path, status="created"))
        except Exception as exc:  # noqa: BLE001
            errors.append(f"{fname}: {exc}")

    def get_deployment_status(self, deployment_id: str, credentials: dict[str, str]) -> DeployResult:
        output_dir = credentials.get("output_dir", "")
        exists     = os.path.isdir(output_dir) if output_dir else False
        return DeployResult(
            status        = DeployStatus.COMPLETE if exists else DeployStatus.UNKNOWN,
            deployment_id = deployment_id,
            message       = f"Artifacts at {output_dir}" if exists else "Output directory not found",
        )

    def rollback(self, deployment_id: str, credentials: dict[str, str]) -> RollbackResult:
        """Remove generated artifact directory."""
        import shutil
        output_dir = credentials.get("output_dir", "")
        if not output_dir or not os.path.isdir(output_dir):
            return RollbackResult(success=True, message="Nothing to remove")
        try:
            shutil.rmtree(output_dir)
            return RollbackResult(success=True, deleted=[output_dir], message=f"Removed {output_dir}")
        except Exception as exc:  # noqa: BLE001
            return RollbackResult(success=False, errors=[str(exc)])
