DOCKER_COMPOSE_TEMPLATE = """\
# Sentryɸ — Generated docker-compose.yml
# Deployment ID: {deployment_id}
# Generated by Sentryɸ {timestamp}

version: "3.9"

services:
  model:
    image: {model_image}
    container_name: sentryphi-model
    restart: unless-stopped
    environment:
      - MODEL_NAME={model_name}
      - MAX_TOKENS={max_tokens}
      - LOG_LEVEL=info
    networks:
      - sentryphi-net
    healthcheck:
      test: ["CMD", "curl", "-f", "http://localhost:8000/health"]
      interval: 30s
      timeout: 10s
      retries: 3
    labels:
      sentryphi: "true"
      deployment-id: "{deployment_id}"

  nginx:
    image: nginx:1.27-alpine
    container_name: sentryphi-nginx
    restart: unless-stopped
    ports:
      - "443:443"
      - "80:80"
    volumes:
      - ./nginx.conf:/etc/nginx/conf.d/default.conf:ro
      - ./certs:/etc/nginx/certs:ro
    depends_on:
      - model
    networks:
      - sentryphi-net
    labels:
      sentryphi: "true"

networks:
  sentryphi-net:
    driver: bridge
"""

NGINX_CONF_TEMPLATE = """\
# Sentryɸ — Generated nginx.conf
# Deployment ID: {deployment_id}

limit_req_zone $binary_remote_addr zone=api:10m rate={rate_limit}r/s;

server {{
    listen 80;
    server_name {domain};
    return 301 https://$server_name$request_uri;
}}

server {{
    listen 443 ssl http2;
    server_name {domain};

    ssl_certificate     /etc/nginx/certs/fullchain.pem;
    ssl_certificate_key /etc/nginx/certs/privkey.pem;
    ssl_protocols       TLSv1.2 TLSv1.3;
    ssl_ciphers         ECDHE-ECDSA-AES128-GCM-SHA256:ECDHE-RSA-AES128-GCM-SHA256;

    limit_req zone=api burst=20 nodelay;

    location /predict {{
        proxy_pass         http://model:8000/predict;
        proxy_set_header   Host $host;
        proxy_set_header   X-Real-IP $remote_addr;
        proxy_read_timeout 300s;
    }}

    location /health {{
        proxy_pass http://model:8000/health;
    }}
}}
"""

